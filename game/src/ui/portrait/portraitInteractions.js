// Each area advances independently; touching another area never skips a line.
export function createPortraitDialogue(characterId) {
  const indices=new Map();
  return area=>{
    const lines=PORTRAIT_REACTIONS[characterId]?.[area];
    if(!lines?.length)return null;
    const index=indices.get(area)||0;indices.set(area,(index+1)%lines.length);
    return lines[index];
  };
}
